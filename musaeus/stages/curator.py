#!/usr/bin/env python3
"""
MUSAEUS — Curator Stage

Builds a car-library export from CATALOGUED files.
Copies audio files into a structured export tree:
    <export_root>/<Artist>/<Album>/<track> - <title>.<ext>

Noise profiles (optional):
  - clean   : no noise tracks
  - pink    : copy Pink_Noise_30min.m4a  (if present in vault)
  - brown   : copy Brown_Noise_60min.m4a
  - dual    : both pink + brown  (default)
  - white   : White_Noise_30min.m4a

Export path and noise variant are stored in archive.car_export_path /
archive.noise_profile.

Rules:
  - dry_run() reports what would be copied — no actual file I/O.
  - Already-exported files whose source hasn't changed are skipped.
  - Destination structure is created as needed.
  - Periodic DB commits every _COMMIT_EVERY files.
"""

from __future__ import annotations

import logging
import re
import shutil
from pathlib import Path

from ..canon.protected_artists import PROTECTED_ARTIST_NAMES
from ..context import RunContext, StageResult
from ..exports import (
    ExportRootError,
    configured_export_root,
    resolve_export_root,
    validate_export_root,
)
from ..filing import load as filing_load
from .base import BaseStage, StageError

logger = logging.getLogger(__name__)

_COMMIT_EVERY = 100

# Ensemble/duo names that must never be split at " & ", for folder naming
# OR for artist-variant folding.
#
# Scope widened 2026-08-21: this list existed and was correct, but a
# one-off artist-fold pass did not consult it and overrode two entries
# (Big Brother & The Holding Company, Barney Bentall & The Legendary
# Hearts) before the damage was spotted and reversed. Any code that
# rewrites archive.artist must check here first -- the whole point of a
# guard list is that it is consulted by everything, not just the stage it
# happened to be written in.
# Re-exported from the single home. Three copies of this list had
# diverged by 2026-09-05 -- organize.py, which names folders, held
# only 6 of the 13 -- so it lives in one place now.
_PROTECTED_ARTIST_NAMES: frozenset[str] = PROTECTED_ARTIST_NAMES

_FEAT_RE = re.compile(
    r"\s+(?:feat\.?|featuring|ft\.?|with|duet with|vs\.?|versus)\s+",
    re.IGNORECASE,
)


def _primary_artist(
    raw: str, mb_artist_name: str | None = None, filing: dict[str, str] | None = None
) -> str:
    """The folder an export files under: the artist folder the masters file
    under (organize.library_artist -- Grey's filing ruling, then MusicBrainz,
    then folder_artist).

    Review of slice B, finding 8: this split names at " & " and "," on its
    own, so canon names were cut back to the short forms artist_canon.tsv
    exists to repair -- "KC & The Sunshine Band" became "KC", "Peter, Paul
    and Mary" became "Peter". Without the MusicBrainz name and the rulings,
    "Ike & Tina Turner" still became "Ike" (review of #163).
    """
    from .organize import library_artist

    return library_artist((raw or "").strip() or "Unknown Artist", mb_artist_name, filing)


# Noise track filenames (generated by musaeus noise-gen or copied manually)
NOISE_FILES: dict[str, list[str]] = {
    "pink": ["Pink_Noise_30min.m4a", "Pink_Noise_60min.m4a"],
    "brown": ["Brown_Noise_60min.m4a", "Brown_Noise_30min.m4a"],
    "white": ["White_Noise_30min.m4a", "White_Noise_60min.m4a"],
}
NOISE_SUBDIR = "Acoustic Treatment"  # subfolder inside export root


def _sanitise(name: str) -> str:
    """Make a string safe for use as a path component."""
    # Windows-safe: strip chars illegal on FAT/NTFS/exFAT
    illegal = r'\/:*?"<>|'
    for ch in illegal:
        name = name.replace(ch, "_")
    return name.strip().strip(".")[:120] or "_unknown_"


def _dest_path(
    export_root: Path, row: dict, noise_subdir: bool = False, filing: dict[str, str] | None = None
) -> Path:
    """Compute the destination file path for one archive row."""
    artist = _sanitise(
        _primary_artist(row.get("artist") or "Unknown Artist", row.get("mb_artist_name"), filing)
    )
    album = _sanitise(row.get("album") or "Unknown Album")
    ext = (row.get("ext") or ".m4a").lower()
    if not ext.startswith("."):
        ext = "." + ext

    track = row.get("track")
    title = _sanitise(row.get("title") or Path(row["file_path"]).stem)

    filename = f"{int(track):02d} - {title}{ext}" if track else f"{title}{ext}"

    return export_root / artist / album / filename


def _free_dest(conn, dst: Path, file_path: str, claimed: set[Path]) -> Path:  # type: ignore[no-untyped-def]
    """*dst*, or "<name> (2)" and so on when another song already has it.

    Review of slice B, finding 8: two songs with the same artist folder, album
    and title (no track number) got one export path, the second copy
    overwrote the first, and both rows recorded that path.
    """
    cand, n = dst, 1
    while (
        cand in claimed
        or conn.execute(
            "SELECT 1 FROM archive WHERE car_export_path = ? AND file_path <> ?",
            (str(cand), file_path),
        ).fetchone()
    ):
        n += 1
        cand = dst.with_name(f"{dst.stem} ({n}){dst.suffix}")
    claimed.add(cand)
    return cand


class CuratorStage(BaseStage):
    """
    Assemble a car-library export from the catalogued archive.

    Configuration via ctx stash:
        ctx.set("curator_export_root", Path("/mnt/USB"))
        ctx.set("curator_noise",       "dual")   # clean|pink|brown|white|dual
        ctx.set("curator_force",       False)     # re-copy even if unchanged
    """

    NAME = "curator"

    def validate(self, ctx: RunContext) -> None:
        """Fail closed before the stage builds or creates anything.

        Previously this accepted any non-None value and explicitly did not
        require it to exist, and run() then called
        `export_root.mkdir(parents=True, exist_ok=True)` -- so a typo in
        --export-root built a new library tree somewhere nobody chose and
        reported success copying into it. The root must now exist, be a
        writable directory, be absolute, and not overlap the library it is
        derived from. Nothing here creates a directory."""
        resolved = resolve_export_root(
            override=ctx.get("curator_export_root"),
            configured=configured_export_root(ctx.config),
        )
        try:
            validated = validate_export_root(
                resolved,
                protected_roots=(ctx.config.alac_library, ctx.config.vault_root),
            )
        except ExportRootError as exc:
            raise StageError(f"{exc}\n  -> {exc.remediation}") from exc

        # Record the resolved value as a redacted identity, not a path.
        ctx.set("curator_export_root_identity", validated.identity)
        ctx.set("curator_export_root_source", validated.source)

    # ── helpers ───────────────────────────────────────────────────────────────

    def _get_export_root(self, ctx: RunContext) -> Path | None:
        """Resolve the export root: one-invocation override, then typed
        configuration, then nothing. No hidden default -- a default export
        root is a directory the operator did not choose, holding a copy of
        their library."""
        resolved = resolve_export_root(
            override=ctx.get("curator_export_root"),
            configured=configured_export_root(ctx.config),
        )
        return None if resolved is None else resolved.path

    def _get_noise_mode(self, ctx: RunContext) -> str:
        return str(ctx.get("curator_noise", "dual"))

    def _get_pending(self, ctx: RunContext, force: bool) -> list[dict]:
        cols = {r[1] for r in ctx.conn.execute("PRAGMA table_info(archive)")}
        mb = "mb_artist_name" if "mb_artist_name" in cols else "NULL AS mb_artist_name"
        if force:
            rows = ctx.conn.execute(
                f"""
                SELECT file_path, artist, {mb}, album, title, track, ext, audio_hash
                  FROM archive
                 WHERE status = 'CATALOGUED'
                 ORDER BY artist, album, track
                """
            ).fetchall()
        else:
            rows = ctx.conn.execute(
                f"""
                SELECT file_path, artist, {mb}, album, title, track, ext, audio_hash
                  FROM archive
                 WHERE status = 'CATALOGUED'
                   AND (car_export_path IS NULL OR car_export_path = '')
                 ORDER BY artist, album, track
                """
            ).fetchall()
        return [dict(r) for r in rows]

    def _find_noise_files(self, ctx: RunContext) -> list[Path]:
        """Locate noise track files in the vault."""
        vault = ctx.vault_root
        noise_dir = vault / "Noise"
        found: list[Path] = []
        for p in [vault, noise_dir]:
            if p.exists():
                for f in p.rglob("*.m4a"):
                    found.append(f)
        return found

    def _select_noise_files(self, noise_mode: str, all_noise: list[Path]) -> list[Path]:
        """Filter noise files by mode."""
        if noise_mode == "clean":
            return []
        keywords = []
        if noise_mode in NOISE_FILES:
            keywords = [kw.lower() for kw in NOISE_FILES[noise_mode]]
        elif noise_mode == "dual":
            keywords = ["pink", "brown"]
        else:
            keywords = []

        if not keywords:
            return all_noise  # 'all' mode
        return [f for f in all_noise if any(kw in f.stem.lower() for kw in keywords)]

    def _copy_file(self, src: Path, dst: Path) -> bool:
        """Copy src → dst, creating parent dirs. Returns True on success.
        Guards against TOCTOU race: file may vanish between exists() check and copy."""
        try:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(str(src), str(dst))
            return True
        except FileNotFoundError:
            logger.warning("curator: source vanished before copy: %s", src)
            return False
        except Exception as exc:
            logger.warning("curator copy failed %s → %s: %s", src, dst, exc)
            return False

    def _save_export_path(
        self, ctx: RunContext, file_path: str, dest: Path, noise_profile: str
    ) -> None:
        ctx.conn.execute(
            """
            UPDATE archive
               SET car_export_path = ?,
                   noise_profile   = ?
             WHERE file_path = ?
            """,
            (str(dest), noise_profile, file_path),
        )
        ctx.log_event(
            "CURATOR_COPY",
            file_path=file_path,
            new_value=str(dest),
            stage="curator",
        )

    # ── run ───────────────────────────────────────────────────────────────────

    def verify_effect(self, ctx: RunContext, result: StageResult) -> list[str]:
        """An exported file must exist at the path the row now advertises.

        Curator copies into the export tree and records car_export_path.
        A copy that failed part-way, or onto a full or unmounted device,
        still leaves the row saying where the file "is". The export is
        then a list of promises rather than a library, and nothing notices
        until it is plugged into a car.

        Checks existence AND non-zero size: a truncated copy is the
        failure mode a bare exists() misses, and an empty file passes it.
        """
        rows = ctx.conn.execute(
            """
            SELECT a.car_export_path FROM archive a
              JOIN events e ON e.file_path = a.file_path
             WHERE e.event_type = 'CURATOR_COPY' AND e.run_id = ?
               AND a.car_export_path IS NOT NULL AND a.car_export_path <> ''
             ORDER BY e.id DESC LIMIT 8
            """,
            (ctx.run_id,),
        ).fetchall()
        if not rows:
            return []
        problems: list[str] = []
        for r in rows:
            p = Path(r["car_export_path"])
            if not p.exists():
                problems.append(f"exported file is not there: {p.name}")
            elif p.stat().st_size == 0:
                problems.append(f"exported file is empty: {p.name}")
        return problems

    def run(self, ctx: RunContext) -> StageResult:
        result = self._make_result(dry_run=False)
        export_root = self._get_export_root(ctx)
        noise_mode = self._get_noise_mode(ctx)
        force: bool = ctx.get("curator_force", False)

        export_root.mkdir(parents=True, exist_ok=True)  # type: ignore[union-attr]

        pending = self._get_pending(ctx, force)
        filing = filing_load(ctx.config.meta_dir)
        total = len(pending)
        result.notes.append(f"files to export : {total}")
        result.notes.append(f"export root     : {export_root}")
        result.notes.append(f"noise mode      : {noise_mode}")

        copied = 0
        skipped = 0
        errors = 0
        claimed: set[Path] = set()  # export paths given out this run

        for i, row in enumerate(pending, 1):
            src = Path(row["file_path"])
            if not src.exists():
                result.files_skipped += 1
                skipped += 1
                continue

            dst = _free_dest(
                ctx.conn,
                _dest_path(export_root, row, filing=filing),  # type: ignore[arg-type]
                row["file_path"],
                claimed,
            )

            # Skip if dest already exists and is same size (idempotent)
            if not force and dst.exists() and dst.stat().st_size == src.stat().st_size:
                result.files_skipped += 1
                skipped += 1
                self._save_export_path(ctx, row["file_path"], dst, noise_mode)
                continue

            ok = self._copy_file(src, dst)
            result.files_processed += 1
            if ok:
                result.files_changed += 1
                copied += 1
                self._save_export_path(ctx, row["file_path"], dst, noise_mode)
            else:
                result.files_errored += 1
                errors += 1

            if i % _COMMIT_EVERY == 0:
                ctx.conn.commit()
                logger.info("curator: checkpoint %d/%d", i, total)

        # Noise tracks
        if noise_mode != "clean":
            all_noise = self._find_noise_files(ctx)
            noise_files = self._select_noise_files(noise_mode, all_noise)
            noise_dest_dir = export_root / NOISE_SUBDIR  # type: ignore[operator]
            for nf in noise_files:
                dst = noise_dest_dir / nf.name
                if not dst.exists():
                    ok = self._copy_file(nf, dst)
                    if ok:
                        result.notes.append(f"  noise: {nf.name}")
                    else:
                        result.notes.append(f"  noise FAILED: {nf.name}")
            if not noise_files:
                result.notes.append(
                    f"  noise: no files found for mode '{noise_mode}' "
                    "(place them in <vault>/Noise/)"
                )

        ctx.conn.commit()

        result.notes.append(f"  copied  : {copied}")
        result.notes.append(f"  skipped : {skipped}")
        if errors:
            result.notes.append(f"  errors  : {errors}")
            result.success = False

        ctx.record_stage(result)
        return result

    # ── dry_run ───────────────────────────────────────────────────────────────

    def dry_run(self, ctx: RunContext) -> StageResult:
        result = self._make_result(dry_run=True)
        export_root = self._get_export_root(ctx)
        noise_mode = self._get_noise_mode(ctx)
        force: bool = ctx.get("curator_force", False)

        pending = self._get_pending(ctx, force)
        filing = filing_load(ctx.config.meta_dir)
        total = len(pending)

        would_copy = 0
        would_skip = 0
        for row in pending:
            src = Path(row["file_path"])
            if not src.exists():
                would_skip += 1
                continue
            dst = _dest_path(export_root, row, filing=filing)  # type: ignore[arg-type]
            if not force and dst.exists() and dst.stat().st_size == src.stat().st_size:
                would_skip += 1
            else:
                would_copy += 1

        noise_count = len(self._select_noise_files(noise_mode, self._find_noise_files(ctx)))

        result.files_processed = total
        result.files_changed = would_copy
        result.files_skipped = would_skip
        result.notes.append(f"[DRY RUN] export root : {export_root}")
        result.notes.append(f"[DRY RUN] noise mode  : {noise_mode} ({noise_count} file(s) found)")
        result.notes.append(f"[DRY RUN] would copy  : {would_copy}")
        result.notes.append(f"[DRY RUN] already ok  : {would_skip}")

        ctx.record_stage(result)
        return result
